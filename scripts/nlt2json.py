"""Rejouable : tables de mortalité ONS 2022-2024 → src/data/life-tables-2022-2024.json.
Usage : python3 -I nlt2json.py <dossier des xlsx> <sortie.json>"""
import openpyxl, json, sys, os
D, OUT = sys.argv[1], sys.argv[2]
files = {'uk': 'nltuk.xlsx', 'england': 'nlt-england.xlsx', 'wales': 'nlt-wales.xlsx', 'scotland': 'nlt-scotland.xlsx', 'ni': 'nlt-ni.xlsx'}
res = {}
for area, f in files.items():
    wb = openpyxl.load_workbook(os.path.join(D, f), read_only=True)
    pub = list(wb['Contents'].iter_rows(values_only=True))[5][0]
    ws = wb['2022-2024']
    qm, qf, em, ef = [], [], [], []
    for r in ws.iter_rows(values_only=True):
        if isinstance(r[0], int) and isinstance(r[7], int):
            assert r[0] == len(qm) and r[7] == len(qf)
            qm.append(r[2]); em.append(r[5]); qf.append(r[9]); ef.append(r[12])
    assert len(qm) == 101 and len(qf) == 101, (area, len(qm))
    res[area] = {'qx': {'m': qm, 'f': qf}, 'ex': {'m': em, 'f': ef}}
    print(area, len(qm), 'âges ;', pub, '; e0', em[0], ef[0], '; q40', qm[40], qf[40])
out = {'_about': 'ONS National life tables 2022-2024, period tables, published 10 December 2025 (Open Government Licence v3.0). qx = probability that a person aged exactly x dies before x+1; ex = period life expectancy at exact age x. Ages 0 to 100. Generated by scripts/nlt2json.py from the ONS reference tables.', 'period': '2022-2024', 'published': '2025-12-10', 'areas': res}
json.dump(out, open(OUT, 'w'), separators=(',', ':'))
